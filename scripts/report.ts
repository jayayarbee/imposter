import { it } from "vitest";
import fs from "node:fs";
import { BUILT_IN } from "@/data";
import { checkPairs, wordReuse } from "@/lib/validation/pairs";
import { coverageReport, crossCategoryDuplicates, validateBank } from "@/lib/validation/bank";
import { DIFFICULTIES } from "@/types";

const TARGET_WORDS = 150; // lower bound of the 150-200 per category per difficulty goal

it("writes docs/DATA_REPORT.md", () => {
  const bank = BUILT_IN.bank;
  const rows = coverageReport(bank);
  const { errors, flags } = checkPairs(bank);
  const count = (xs: (string | undefined)[]) => {
    const m = new Map<string, number>();
    for (const x of xs) if (x) m.set(x, (m.get(x) ?? 0) + 1);
    return [...m.entries()].sort((a, b) => b[1] - a[1]);
  };
  const rel = count(bank.pairs.map((p) => p.relationship));
  const tags = count(bank.pairs.flatMap((p) => p.tags ?? []));
  const reuse = wordReuse(bank).filter((w) => w.pairs > 1).slice(0, 25);
  const classic = bank.words.filter((w) => !w.pairOnly).length;
  const concepts = bank.words.filter((w) => w.pairOnly).length;
  const L: string[] = [];
  L.push("# Data report", "", "_Generated by `npm run report` from the actual data files. Do not edit by hand._", "");
  L.push("## Totals", "");
  L.push(`- Individual words (classic mode): **${classic}**`);
  L.push(`- Association pairs (different-word mode): **${bank.pairs.length}**`);
  L.push(`- Unique concepts used inside pairs: **${concepts}**`);
  L.push(`- Structural problems: ${validateBank(bank).length}; pair errors: ${errors.length}; near-synonym flags: ${flags.length}`);
  L.push(`- Cross-category duplicate words: ${crossCategoryDuplicates(bank).length}`, "");
  L.push("## Coverage by category and difficulty", "", "| Category | Words E | Words M | Words H | Pairs E | Pairs M | Pairs H |", "|---|---:|---:|---:|---:|---:|---:|");
  for (const r of rows) L.push(`| ${r.label} | ${r.words.easy} | ${r.words.medium} | ${r.words.hard} | ${r.pairs.easy} | ${r.pairs.medium} | ${r.pairs.hard} |`);
  L.push("", `## Shortfall against the ${TARGET_WORDS}-word-per-cell target`, "", "| Category | Easy | Medium | Hard |", "|---|---:|---:|---:|");
  for (const r of rows) L.push(`| ${r.label} | ${DIFFICULTIES.map((d) => `${Math.round((r.words[d] / TARGET_WORDS) * 100)}%`).join(" | ")} |`);
  L.push("", "## Relationship types", "", ...rel.map(([k, v]) => `- ${k}: ${v}`));
  L.push("", "## Regional / subject tags", "", ...tags.map(([k, v]) => `- ${k}: ${v}`));
  L.push("", "## Most reused concepts (appear in more than one pair)", "", ...(reuse.length ? reuse.map((w) => `- ${w.word}: ${w.pairs}`) : ["- none"]));
  L.push("", "## Review flags", "", ...(flags.length ? flags.map((f) => `- ${f.pairId}: ${f.problem}`) : ["- none"]), "");
  fs.mkdirSync("docs", { recursive: true });
  fs.writeFileSync("docs/DATA_REPORT.md", L.join("\n"));
});
